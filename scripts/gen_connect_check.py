#!/usr/bin/env python3
"""Generate the connection-check step texts from protocol/connect-check.json.

Writes:
  desktop/frontend/src/generated/connect-check.json          desktop app (strings.ts)
  ide/pycharm-plugin/.../XScriptBundle{,_zh_CN}.properties   PyCharm (block between the "connect-check" markers)
  ide/vscode-extension/src/generated/connectCheck.ts         VS Code extension
  docs/TROUBLESHOOTING.md                                     the step table (block between the markers)

--check fails when any output is stale, or when a step points at a TROUBLESHOOTING.md section that does not exist.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "protocol" / "connect-check.json"
DESKTOP = ROOT / "desktop/frontend/src/generated/connect-check.json"
PYCHARM = {"en": ROOT / "ide/pycharm-plugin/src/main/resources/messages/XScriptBundle.properties",
           "zh": ROOT / "ide/pycharm-plugin/src/main/resources/messages/XScriptBundle_zh_CN.properties"}
VSCODE = ROOT / "ide/vscode-extension/src/generated/connectCheck.ts"
DOC = ROOT / "docs/TROUBLESHOOTING.md"
P_BEGIN, P_END = "# BEGIN generated: connect-check (scripts/gen_connect_check.py)", "# END generated: connect-check"
D_BEGIN, D_END = "<!-- BEGIN generated: connect-check (scripts/gen_connect_check.py) -->", "<!-- END generated: connect-check -->"
LANGS = ("zh", "en")
CLIENTS = ("desktop", "pycharm", "vscode")


def load():
    steps = json.loads(SRC.read_text(encoding="utf-8"))["steps"]
    for s in steps:
        assert re.fullmatch(r"[a-z]+", s["id"]), s["id"]
        assert set(s["clients"]) <= set(CLIENTS) and s["clients"], s["id"]
        for key in ("title", "fix", "fixIde"):
            if key in s:
                assert set(s[key]) == set(LANGS) and all(s[key][l].strip() for l in LANGS), (s["id"], key)
    return steps


def fix_for(step, client, lang):
    if client != "desktop" and "fixIde" in step:
        return step["fixIde"][lang]
    return step["fix"][lang]


def for_client(steps, client):
    return [s for s in steps if client in s["clients"]]


def desktop_json(steps):
    out = {l: {s["id"]: {"title": s["title"][l], "fix": fix_for(s, "desktop", l)} for s in for_client(steps, "desktop")} for l in LANGS}
    return json.dumps(out, ensure_ascii=False, indent=2) + "\n"


def prop_escape(text):
    # MessageFormat: a single quote must be doubled; braces are not used in these texts
    assert "{" not in text and "}" not in text, text
    return text.replace("'", "''")


def pycharm_props(current, steps, lang):
    lines = [P_BEGIN]
    for s in for_client(steps, "pycharm"):
        lines.append("check.%s=%s" % (s["id"], prop_escape(s["title"][lang])))
        lines.append("check.fix.%s=%s" % (s["id"], prop_escape(fix_for(s, "pycharm", lang))))
    lines.append(P_END)
    return replace_block(current, P_BEGIN, P_END, "\n".join(lines), "properties")


def vscode_ts(steps):
    data = [{"id": s["id"], "title": s["title"], "fix": {l: fix_for(s, "vscode", l) for l in LANGS}} for s in for_client(steps, "vscode")]
    return ("// Generated by scripts/gen_connect_check.py from protocol/connect-check.json. Do not edit.\n"
            "export interface ConnectCheckText { id: string; title: { zh: string; en: string }; fix: { zh: string; en: string } }\n"
            "export const CONNECT_CHECK_STEPS: ConnectCheckText[] = " + json.dumps(data, ensure_ascii=False, indent=2) + ";\n")


def doc_block(steps):
    def where(s):
        names = {"desktop": "桌面端", "pycharm": "PyCharm", "vscode": "VS Code"}
        return "、".join(names[c] for c in s["clients"])
    rows = ["| 步骤 | 检查它的工具 | 没通过时怎么修 | 详见 |", "| --- | --- | --- | --- |"]
    for s in steps:
        fix = s["fix"]["zh"]
        if "fixIde" in s:
            fix += "<br>PyCharm / VS Code：" + s["fixIde"]["zh"]
        rows.append("| %s | %s | %s | 第 %d 节 |" % (s["title"]["zh"], where(s), fix.replace("|", "\\|"), s["section"]))
    return "\n".join([D_BEGIN, "", *rows, "", D_END])


def replace_block(text, begin, end, block, what):
    if begin in text:
        i, j = text.index(begin), text.index(end) + len(end)
        return text[:i] + block + text[j:]
    raise SystemExit("%s: markers %r … %r not found" % (what, begin, end))


def sections(doc):
    return {int(m.group(1)) for m in re.finditer(r"^## (\d+)\. ", doc, re.M)}


def main(check):
    steps = load()
    doc = DOC.read_text(encoding="utf-8")
    missing = sorted({s["section"] for s in steps} - sections(doc))
    if missing:
        print("TROUBLESHOOTING.md has no section(s) %s referenced by protocol/connect-check.json" % missing)
        return 1
    outputs = {DESKTOP: desktop_json(steps), DOC: replace_block(doc, D_BEGIN, D_END, doc_block(steps), "TROUBLESHOOTING.md")}
    if for_client(steps, "vscode"):  # the VS Code module exists once a step is shown there
        outputs[VSCODE] = vscode_ts(steps)
    for lang, path in PYCHARM.items():
        outputs[path] = pycharm_props(path.read_text(encoding="utf-8"), steps, lang)
    stale = []
    for path, text in outputs.items():
        old = path.read_text(encoding="utf-8") if path.exists() else None
        if old != text:
            stale.append(path.relative_to(ROOT))
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text, encoding="utf-8")
    if check and stale:
        print("stale (run python scripts/gen_connect_check.py): " + ", ".join(map(str, stale)))
        return 1
    if not check:
        print("updated: " + (", ".join(map(str, stale)) or "nothing"))
    return 0


if __name__ == "__main__":
    sys.exit(main("--check" in sys.argv[1:]))
