#!/usr/bin/env python3
"""Regenerate the Web IDE hover / signature-help index from ide/python-stubs/ (xscript and ascript).

Writes android/app/src/main/assets/tools/editor-docs.js: `XSDocs = {"xscript.android.action.click": [signature, doc]}`,
keyed by the qualified name of every public module, function, class and method. A class's signature is its
constructor's (without self). Names a stub re-exports (`from xscript.android.coords import to_wgs84`) get the entry of
the original, so `location.to_wgs84` shows the converter's docs. Docstrings are kept whole (capped at MAX_DOC chars).
Plain script, so the page works offline.

    python3 scripts/gen_editor_docs.py          # rewrite editor-docs.js
    python3 scripts/gen_editor_docs.py --check  # exit 1 if it is stale
"""
from __future__ import annotations

import argparse
import ast
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "ide" / "python-stubs"
OUT = ROOT / "android" / "app" / "src" / "main" / "assets" / "tools" / "editor-docs.js"
PACKAGES = ("xscript", "ascript")
MAX_DOC = 1500
HEADER = "// Generated by scripts/gen_editor_docs.py from ide/python-stubs/. Do not edit.\n"


def public(name: str) -> bool:
    return not name.startswith("_")


def doc(node) -> str:
    text = (ast.get_docstring(node) or "").strip()
    return text if len(text) <= MAX_DOC else text[:MAX_DOC - 3].rstrip() + "..."


def signature(fn, drop_self: bool) -> str:
    a = fn.args
    params = a.posonlyargs + a.args
    if drop_self and params and params[0].arg in ("self", "cls"):
        if a.posonlyargs:
            a = ast.arguments(posonlyargs=a.posonlyargs[1:], args=a.args, vararg=a.vararg, kwonlyargs=a.kwonlyargs,
                              kw_defaults=a.kw_defaults, kwarg=a.kwarg, defaults=a.defaults)
        else:
            a = ast.arguments(posonlyargs=[], args=a.args[1:], vararg=a.vararg, kwonlyargs=a.kwonlyargs,
                              kw_defaults=a.kw_defaults, kwarg=a.kwarg, defaults=a.defaults)
    ret = " -> " + ast.unparse(fn.returns) if fn.returns is not None else ""
    return "(" + ast.unparse(a) + ")" + ret


def is_static(fn) -> bool:
    return any(isinstance(d, ast.Name) and d.id == "staticmethod" for d in fn.decorator_list)


def add_class(out: dict, key: str, cls: ast.ClassDef) -> None:
    init = next((s for s in cls.body if isinstance(s, (ast.FunctionDef, ast.AsyncFunctionDef)) and s.name == "__init__"), None)
    out[key] = [signature(init, True) if init else "()", doc(cls) or (doc(init) if init else "")]
    for s in cls.body:
        if isinstance(s, (ast.FunctionDef, ast.AsyncFunctionDef)) and public(s.name):
            out[key + "." + s.name] = [signature(s, not is_static(s)), doc(s)]
        elif isinstance(s, ast.ClassDef) and public(s.name):
            add_class(out, key + "." + s.name, s)


def stub_files() -> dict[str, Path]:
    files: dict[str, Path] = {}
    for pkg in PACKAGES:
        for p in sorted((SRC / pkg).rglob("*.pyi")):
            rel = p.relative_to(SRC).with_suffix("")
            parts = list(rel.parts)
            if parts[-1] == "__init__":
                parts.pop()
            if any(not public(x) for x in parts) or "runtime" in parts:
                continue
            files[".".join(parts)] = p
    return files


def build() -> dict:
    out: dict[str, list] = {}
    reexports: list[tuple[str, str]] = []  # (alias key, source key)
    files = stub_files()
    for dotted, path in sorted(files.items()):
        tree = ast.parse(path.read_text(encoding="utf-8"))
        out[dotted] = ["", doc(tree)]
        package = dotted if path.name == "__init__.pyi" else dotted.rpartition(".")[0]
        for s in tree.body:
            if isinstance(s, (ast.FunctionDef, ast.AsyncFunctionDef)) and public(s.name):
                out[dotted + "." + s.name] = [signature(s, False), doc(s)]
            elif isinstance(s, ast.ClassDef) and public(s.name):
                add_class(out, dotted + "." + s.name, s)
            elif isinstance(s, ast.ImportFrom):
                base = s.module or ""
                if s.level:
                    up = package.split(".")[: len(package.split(".")) - (s.level - 1)]
                    base = ".".join(up + ([base] if base else []))
                if base.split(".")[0] not in PACKAGES:
                    continue
                for a in s.names:
                    name = a.asname or a.name
                    if a.name != "*" and public(name):
                        reexports.append((dotted + "." + name, base + "." + a.name))
    for _ in range(4):  # chains of re-exports
        for alias, src in reexports:
            if alias in out:
                continue
            hits = {k: v for k, v in out.items() if k == src or k.startswith(src + ".")}
            for k, v in hits.items():
                out[alias + k[len(src):]] = v
    return dict(sorted((k, v) for k, v in out.items() if v[0] or v[1]))


def render() -> str:
    body = json.dumps(build(), ensure_ascii=False, separators=(",", ":"))
    return (HEADER + "(function (root) {\n  const XSDocs = " + body + ";\n"
            "  if (typeof module !== \"undefined\" && module.exports) module.exports = { XSDocs };\n"
            "  else root.XSDocs = XSDocs;\n})(typeof window !== \"undefined\" ? window : globalThis);\n")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text = render()
    if args.check:
        if not OUT.is_file() or OUT.read_text(encoding="utf-8") != text:
            print("stale:", OUT.relative_to(ROOT), "(run python3 scripts/gen_editor_docs.py)")
            return 1
        return 0
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:  # LF on Windows too
        f.write(text)
    print("wrote %s (%d KB)" % (OUT.relative_to(ROOT), len(text.encode()) // 1024))
    return 0


if __name__ == "__main__":
    sys.exit(main())
