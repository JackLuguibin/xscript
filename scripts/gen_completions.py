#!/usr/bin/env python3
"""Regenerate the Web IDE completion index from android/python-runtime/ (the same public API as ide/python-stubs).

Writes android/app/src/main/assets/tools/editor-api.js: `XSApi = {modules: {"xscript.android.action": {...}}}` with
public functions (signature + first doc line), classes (constructor signature, methods, attributes), constants and
sub-modules. It is a plain script so the page works offline without fetching anything.

    python3 scripts/gen_completions.py          # rewrite editor-api.js
    python3 scripts/gen_completions.py --check  # exit 1 if it is stale
"""
from __future__ import annotations

import argparse
import ast
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "android" / "python-runtime"
OUT = ROOT / "android" / "app" / "src" / "main" / "assets" / "tools" / "editor-api.js"
PACKAGES = ("xscript", "ascript")
SKIP_DIRS = {"__pycache__", "runtime"}  # xscript.runtime is the Kotlin bridge, not script API
HEADER = "// Generated by scripts/gen_completions.py from android/python-runtime/. Do not edit.\n"


def public(name: str) -> bool:
    return not name.startswith("_")


def first_line(node) -> str:
    doc = ast.get_docstring(node) or ""
    line = next((l.strip() for l in doc.splitlines() if l.strip()), "")
    return line if len(line) <= 140 else line[:137] + "..."


def signature(fn, drop_self: bool) -> str:
    args = fn.args
    if drop_self and (args.posonlyargs or args.args) and (args.posonlyargs + args.args)[0].arg in ("self", "cls"):
        args = ast.arguments(posonlyargs=args.posonlyargs[1:] if args.posonlyargs else [],
                             args=args.args[1:] if not args.posonlyargs else args.args,
                             vararg=args.vararg, kwonlyargs=args.kwonlyargs, kw_defaults=args.kw_defaults,
                             kwarg=args.kwarg, defaults=args.defaults)
    text = ast.unparse(args)
    ret = " -> " + ast.unparse(fn.returns) if fn.returns is not None else ""
    return "(" + text + ")" + ret


def is_static(fn) -> bool:
    return any(isinstance(d, ast.Name) and d.id in ("staticmethod", "classmethod") for d in fn.decorator_list)


def class_entry(cls: ast.ClassDef) -> dict:
    members: dict[str, dict] = {}
    init = None
    for stmt in cls.body:
        if isinstance(stmt, (ast.FunctionDef, ast.AsyncFunctionDef)):
            if stmt.name == "__init__":
                init = stmt
            elif public(stmt.name):
                members[stmt.name] = {"k": "f", "s": signature(stmt, drop_self=not is_static(stmt)), "d": first_line(stmt)}
        elif isinstance(stmt, (ast.Assign, ast.AnnAssign)):
            targets = stmt.targets if isinstance(stmt, ast.Assign) else [stmt.target]
            for t in targets:
                if isinstance(t, ast.Name) and public(t.id):
                    members[t.id] = {"k": "v"}
        elif isinstance(stmt, ast.ClassDef) and public(stmt.name):
            members[stmt.name] = {"k": "c", "s": "", "d": first_line(stmt)}
    entry = {"k": "c", "s": signature(init, True) if init else "()", "d": first_line(cls), "m": dict(sorted(members.items()))}
    return entry


def module_entry(path: Path, dotted: str, children: list[str]) -> dict:
    tree = ast.parse(path.read_text(encoding="utf-8")) if path else ast.Module(body=[], type_ignores=[])
    members: dict[str, dict] = {}
    for stmt in tree.body:
        if isinstance(stmt, (ast.FunctionDef, ast.AsyncFunctionDef)) and public(stmt.name):
            members[stmt.name] = {"k": "f", "s": signature(stmt, False), "d": first_line(stmt)}
        elif isinstance(stmt, ast.ClassDef) and public(stmt.name):
            members[stmt.name] = class_entry(stmt)
        elif isinstance(stmt, (ast.Assign, ast.AnnAssign)):
            targets = stmt.targets if isinstance(stmt, ast.Assign) else [stmt.target]
            for t in targets:
                if isinstance(t, ast.Name) and public(t.id):
                    members.setdefault(t.id, {"k": "v"})
        elif isinstance(stmt, ast.ImportFrom) and not (stmt.module or "").startswith("xscript.runtime"):
            for alias in stmt.names:  # re-exports from package __init__ files
                name = alias.asname or alias.name
                if name != "*" and public(name) and stmt.level + len((stmt.module or "").split(".")) >= 1:
                    members.setdefault(name, {"k": "v"})
    for child in children:
        members[child] = {"k": "m"}
    return {"d": first_line(tree), "m": dict(sorted(members.items()))}


def build() -> dict:
    modules: dict[str, dict] = {}
    for pkg in PACKAGES:
        base = SRC / pkg
        files: dict[str, Path] = {}
        for src in sorted(base.rglob("*.py")):
            rel = src.relative_to(SRC)
            if SKIP_DIRS.intersection(rel.parts[:-1]) or any(p.startswith("_") and p != "__init__.py" for p in rel.parts):
                continue
            parts = list(rel.with_suffix("").parts)
            if parts[-1] == "__init__":
                parts.pop()
            files[".".join(parts)] = src
        for dotted in sorted(files):
            kids = sorted({d[len(dotted) + 1:].split(".")[0] for d in files if d.startswith(dotted + ".")})
            modules[dotted] = module_entry(files[dotted], dotted, kids)
        # virtual parents without an __init__.py (e.g. a namespace directory)
        for dotted in list(files):
            parts = dotted.split(".")
            for i in range(1, len(parts)):
                parent = ".".join(parts[:i])
                if parent not in modules:
                    kids = sorted({d[len(parent) + 1:].split(".")[0] for d in files if d.startswith(parent + ".")})
                    modules[parent] = module_entry(None, parent, kids)
    return {"modules": dict(sorted(modules.items()))}


def render() -> str:
    body = json.dumps(build(), ensure_ascii=False, separators=(",", ":"), sort_keys=False)
    return (HEADER + "(function (root) {\n  const XSApi = " + body + ";\n"
            "  if (typeof module !== \"undefined\" && module.exports) module.exports = { XSApi };\n"
            "  else root.XSApi = XSApi;\n})(typeof window !== \"undefined\" ? window : globalThis);\n")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text = render()
    if args.check:
        if not OUT.is_file() or OUT.read_text(encoding="utf-8") != text:
            print("stale:", OUT.relative_to(ROOT))
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    print("wrote %s (%d KB)" % (OUT.relative_to(ROOT), len(text.encode()) // 1024))
    return 0


if __name__ == "__main__":
    sys.exit(main())
