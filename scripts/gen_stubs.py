#!/usr/bin/env python3
"""Regenerate python-stubs/ from python-runtime/ so PC autocomplete matches the device API.

Keeps module/class/function signatures, docstrings, class attributes and module constants;
drops bodies and private (_underscore) helpers. Output is .pyi files, which editors use for
completion without being importable at runtime.

    python3 scripts/gen_stubs.py          # rewrite python-stubs/{xscript,ascript}
    python3 scripts/gen_stubs.py --check  # exit 1 if stubs are stale
"""
from __future__ import annotations

import argparse
import ast
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "python-runtime"
OUT = ROOT / "python-stubs"
PACKAGES = ("xscript", "ascript")
SKIP_DIRS = {"__pycache__", "runtime"}  # xscript.runtime is the Kotlin bridge, not script API
HEADER = "# Generated by scripts/gen_stubs.py from python-runtime/. Do not edit.\n"


def _public(name: str) -> bool:
    return not name.startswith("_") or (name.startswith("__") and name.endswith("__"))


def _doc(node) -> list[ast.stmt]:
    d = ast.get_docstring(node, clean=False)
    return [ast.Expr(ast.Constant(d))] if d else []


def _ellipsis() -> ast.stmt:
    return ast.Expr(ast.Constant(...))


def _func(fn):
    body = _doc(fn) or [_ellipsis()]
    if len(body) == 1 and not isinstance(body[0].value.value, type(...)):
        body.append(_ellipsis())
    new = type(fn)(
        name=fn.name, args=fn.args, body=body, decorator_list=fn.decorator_list,
        returns=fn.returns, type_comment=None,
    )
    if sys.version_info >= (3, 12):
        new.type_params = getattr(fn, "type_params", [])
    return new


def _assign_stub(stmt):
    """Keep simple NAME = <literal> assignments; replace other values with `...`."""
    targets = stmt.targets if isinstance(stmt, ast.Assign) else [stmt.target]
    names = [t for t in targets if isinstance(t, ast.Name) and _public(t.id)]
    if not names:
        return None
    value = getattr(stmt, "value", None)
    try:
        ast.literal_eval(value)
        keep = value
    except Exception:
        keep = ast.Constant(...)
    if isinstance(stmt, ast.AnnAssign):
        return ast.AnnAssign(target=names[0], annotation=stmt.annotation, value=keep, simple=1)
    return ast.Assign(targets=names, value=keep, lineno=0)


def _class(cls):
    body = _doc(cls)
    for stmt in cls.body:
        if isinstance(stmt, (ast.FunctionDef, ast.AsyncFunctionDef)) and _public(stmt.name):
            body.append(_func(stmt))
        elif isinstance(stmt, (ast.Assign, ast.AnnAssign)):
            s = _assign_stub(stmt)
            if s is not None:
                body.append(s)
        elif isinstance(stmt, ast.ClassDef) and _public(stmt.name):
            body.append(_class(stmt))
    if not body:
        body = [_ellipsis()]
    new = ast.ClassDef(name=cls.name, bases=cls.bases, keywords=cls.keywords, body=body,
                       decorator_list=cls.decorator_list)
    if sys.version_info >= (3, 12):
        new.type_params = getattr(cls, "type_params", [])
    return new


def stub_module(source: str) -> str:
    tree = ast.parse(source)
    body = _doc(tree)
    for stmt in tree.body:
        if isinstance(stmt, ast.ImportFrom) and (stmt.module or "").startswith("xscript.runtime"):
            continue  # device bridge, not shipped in the stubs
        if isinstance(stmt, (ast.Import, ast.ImportFrom)):
            body.append(stmt)
        elif isinstance(stmt, (ast.FunctionDef, ast.AsyncFunctionDef)) and _public(stmt.name):
            body.append(_func(stmt))
        elif isinstance(stmt, ast.ClassDef) and _public(stmt.name):
            body.append(_class(stmt))
        elif isinstance(stmt, (ast.Assign, ast.AnnAssign)):
            s = _assign_stub(stmt)
            if s is not None:
                body.append(s)
        elif isinstance(stmt, ast.Try):
            # optional imports like `try: import cv2 except ImportError: cv2 = None`
            for sub in stmt.body:
                if isinstance(sub, (ast.Import, ast.ImportFrom)):
                    body.append(sub)
    mod = ast.Module(body=body, type_ignores=[])
    return HEADER + ast.unparse(ast.fix_missing_locations(mod)) + "\n"


def build() -> dict[Path, str]:
    out: dict[Path, str] = {}
    for pkg in PACKAGES:
        for src in sorted((SRC / pkg).rglob("*.py")):
            rel = src.relative_to(SRC)
            if SKIP_DIRS.intersection(rel.parts[:-1]):
                continue
            out[OUT / rel.with_suffix(".pyi")] = stub_module(src.read_text(encoding="utf-8"))
    return out


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    files = build()
    existing = {p for pkg in PACKAGES for p in (OUT / pkg).rglob("*.py*") if "__pycache__" not in p.parts}
    stale = [p for p, text in files.items() if not p.is_file() or p.read_text(encoding="utf-8") != text]
    extra = sorted(existing - set(files))
    if args.check:
        for p in stale + extra:
            print("stale:", p.relative_to(ROOT))
        return 1 if stale or extra else 0
    for p in extra:
        p.unlink()
    for p, text in files.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text, encoding="utf-8")
    print("wrote %d stub files (removed %d)" % (len(files), len(extra)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
