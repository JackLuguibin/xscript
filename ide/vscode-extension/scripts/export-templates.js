// Writes the new-project templates (src/newProject.ts TEMPLATES) to ../pycharm-plugin/src/main/resources/templates.json
// so the PyCharm plugin offers exactly the same set. Needs `npm run compile` first (reads out/newProject.js).
// usage: node scripts/export-templates.js [--check]   (--check: fail if the committed file is out of date; CI runs it)
const fs = require("fs");
const path = require("path");
const { TEMPLATES } = require("../out/newProject.js");

const NAME = "__XSCRIPT_PROJECT_NAME__"; // project names are letters/digits/underscores, so a plain replace is safe
const dest = path.resolve(__dirname, "..", "..", "pycharm-plugin", "src", "main", "resources", "templates.json");
const data = {
  _comment: "Generated by ide/vscode-extension/scripts/export-templates.js from src/newProject.ts; do not edit.",
  name_placeholder: NAME,
  templates: TEMPLATES.map((t) => ({ id: t.id, label: t.label, detail: t.detail, files: t.files(NAME) })),
};
const text = JSON.stringify(data, null, 2) + "\n";
if (process.argv.includes("--check")) {
  const old = fs.existsSync(dest) ? fs.readFileSync(dest, "utf-8") : "";
  if (old !== text) {
    console.error(path.relative(process.cwd(), dest) + " is out of date: run node scripts/export-templates.js");
    process.exit(1);
  }
  console.log("templates.json up to date (" + data.templates.length + " templates)");
} else {
  fs.writeFileSync(dest, text, "utf-8");
  console.log("wrote " + path.relative(process.cwd(), dest) + " (" + data.templates.length + " templates)");
}
