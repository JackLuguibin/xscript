import { readFileSync } from "node:fs";
import { resolve } from "node:path";
import { describe, expect, it } from "vitest";
import { uiForm } from "../src/ui-form";

describe("UI designer core (shared with VS Code / Web IDE)", () => {
  it("the vendored copy is byte-identical to android/app/src/main/assets/tools/ui-form.js", () => {
    const src = readFileSync(resolve(__dirname, "../../../android/app/src/main/assets/tools/ui-form.js"), "utf8");
    const copy = readFileSync(resolve(__dirname, "../src/vendor/ui-form.js"), "utf8");
    expect(copy === src, "re-copy: cp android/app/src/main/assets/tools/ui-form.js desktop/frontend/src/vendor/").toBe(true);
  });

  it("loads in the page and generates the same two files the other designers do", () => {
    const spec = uiForm.newSpec("设置");
    spec.fields.push(uiForm.newField("text", spec), uiForm.newField("checkbox", spec));
    expect(uiForm.validateSpec(spec)).toEqual([]);
    const out = uiForm.outputs(spec, "main");
    expect(Object.keys(out).sort()).toEqual(["res/ui/main.html", "ui_main.py"]);
    expect(out["ui_main.py"]).toContain("# Generated by the XScript UI designer");
    expect(out["res/ui/main.html"]).toContain("<form");
    expect(uiForm.parseSpec(uiForm.serializeSpec(spec))).toEqual(spec);
    expect(uiForm.formName("res/ui/登录.ui.json")).toBe("登录");
  });
});
